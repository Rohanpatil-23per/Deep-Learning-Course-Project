import os
import logging
from typing import List, Dict, Any, Optional
from neo4j import GraphDatabase, Driver

logger = logging.getLogger("immunex.neo4j")

NEO4J_URI = os.getenv("NEO4J_URI", "bolt://localhost:7687")
NEO4J_USER = os.getenv("NEO4J_USER", "neo4j")
NEO4J_PASSWORD = os.getenv("NEO4J_PASSWORD", "immunex_neo4j_password")

class IMMUNEXNeo4j:
    """
    Neo4j Graph Database Client for IMMUNEX attack graph generation and tracking.
    """
    def __init__(self, uri: str = NEO4J_URI, user: str = NEO4J_USER, password: str = NEO4J_PASSWORD):
        self._uri = uri
        self._auth = (user, password)
        self._driver: Optional[Driver] = None
        self._connect()

    def _connect(self):
        try:
            self._driver = GraphDatabase.driver(self._uri, auth=self._auth)
            self._driver.verify_connectivity()
            logger.info("Connected to Neo4j at %s", self._uri)
        except Exception as e:
            logger.warning("Neo4j connection failed: %s. Graph operations will be mocked/skipped.", e)
            self._driver = None

    def is_connected(self) -> bool:
        if self._driver is None:
            self._connect()
        return self._driver is not None

    def close(self):
        if self._driver:
            self._driver.close()
            self._driver = None

    def run_queries(self, queries: List[tuple]) -> bool:
        """
        Executes a list of (cypher_query, params_dict) parameterized tuples in a transaction.
        """
        if not self.is_connected():
            logger.warning("Neo4j is not connected. Skipping queries.")
            return False

        try:
            with self._driver.session() as session:
                def _tx_work(tx):
                    for q, params in queries:
                        tx.run(q, **params)
                session.execute_write(_tx_work)
            return True
        except Exception as e:
            logger.error("Failed executing Neo4j batch queries: %s", e)
            return False

    def commit_attack_graph(self, events: List[Dict[str, Any]], attack_uuid: str) -> bool:
        """
        Commits an attack chain graph to Neo4j using queries generated by graph_builder.
        """
        try:
            from layer2_correlation.graph_builder import generate_neo4j_pre_approval_commit
            queries = generate_neo4j_pre_approval_commit(events, attack_uuid)
            return self.run_queries(queries)
        except Exception as e:
            logger.error("Failed to commit attack graph for incident %s: %s", attack_uuid, e)
            return False

    def commit_post_approval(self, attack_uuid: str, action: str, admin: str, status: str = "COMPLETED") -> bool:
        """
        Records the incident response decision into the Neo4j attack graph.
        """
        if not self.is_connected():
            return False
        try:
            from layer2_correlation.graph_builder import generate_neo4j_post_approval_commit
            cypher = generate_neo4j_post_approval_commit(attack_uuid, action, admin, status)
            with self._driver.session() as session:
                session.run(cypher)
            return True
        except Exception as e:
            logger.error("Failed to record post-approval node in Neo4j for %s: %s", attack_uuid, e)
            return False

    def get_incident_subgraph(self, attack_uuid: str) -> Dict[str, Any]:
        """
        Retrieves the nodes and edges for an incident graph in a format ready for visualization.
        """
        if not self.is_connected():
            return {"nodes": [], "edges": []}

        cypher = """
        MATCH (i:Incident {incident_id: $incident_id})
        OPTIONAL MATCH (i)-[r1:CONTAINS]->(a:Alert)
        OPTIONAL MATCH (a)-[r2:ORIGINATES_FROM]->(m:Machine)
        OPTIONAL MATCH (a)-[r3:INVOLVES]->(f:File)
        OPTIONAL MATCH (a)-[r4:PERFORMED_BY]->(u:User)
        OPTIONAL MATCH (i)-[r5:RESPONDED_WITH]->(resp:Response)
        RETURN i, a, m, f, u, resp
        """
        try:
            nodes = []
            edges = []
            seen_nodes = set()

            with self._driver.session() as session:
                results = session.run(cypher, incident_id=attack_uuid)
                for record in results:
                    # Add Incident node
                    inc = record.get("i")
                    if inc and inc.element_id not in seen_nodes:
                        seen_nodes.add(inc.element_id)
                        nodes.append({"id": inc["incident_id"], "label": "Incident", "type": "Incident", "properties": dict(inc)})

                    # Add Alert node
                    alert = record.get("a")
                    if alert and alert.element_id not in seen_nodes:
                        seen_nodes.add(alert.element_id)
                        nodes.append({"id": alert["alert_id"], "label": f"Alert {alert.get('alert_id')}", "type": "Alert", "properties": dict(alert)})
                        if inc:
                            edges.append({"source": inc["incident_id"], "target": alert["alert_id"], "relationship": "CONTAINS"})

                    # Add Machine node
                    machine = record.get("m")
                    if machine and machine.element_id not in seen_nodes:
                        seen_nodes.add(machine.element_id)
                        nodes.append({"id": machine["ip"], "label": machine["ip"], "type": "Machine", "properties": dict(machine)})
                        if alert:
                            edges.append({"source": alert["alert_id"], "target": machine["ip"], "relationship": "ORIGINATES_FROM"})

                    # Add File node
                    file_node = record.get("f")
                    if file_node and file_node.element_id not in seen_nodes:
                        seen_nodes.add(file_node.element_id)
                        nodes.append({"id": file_node["path"], "label": file_node["path"], "type": "File", "properties": dict(file_node)})
                        if alert:
                            edges.append({"source": alert["alert_id"], "target": file_node["path"], "relationship": "INVOLVES"})

                    # Add User node
                    user_node = record.get("u")
                    if user_node and user_node.element_id not in seen_nodes:
                        seen_nodes.add(user_node.element_id)
                        nodes.append({"id": user_node["username"], "label": user_node["username"], "type": "User", "properties": dict(user_node)})
                        if alert:
                            edges.append({"source": alert["alert_id"], "target": user_node["username"], "relationship": "PERFORMED_BY"})

                    # Add Response node
                    resp_node = record.get("resp")
                    if resp_node and resp_node.element_id not in seen_nodes:
                        seen_nodes.add(resp_node.element_id)
                        nodes.append({"id": f"resp_{attack_uuid}", "label": resp_node["action"], "type": "Response", "properties": dict(resp_node)})
                        if inc:
                            edges.append({"source": inc["incident_id"], "target": f"resp_{attack_uuid}", "relationship": "RESPONDED_WITH"})

            return {"nodes": nodes, "edges": edges}
        except Exception as e:
            logger.error("Failed to fetch graph from Neo4j: %s", e)
            return {"nodes": [], "edges": []}
